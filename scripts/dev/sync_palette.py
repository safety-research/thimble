#!/usr/bin/env python3
"""Write the terminal UI's palette from the browser's tokens, so one card has the same colors in both.

    python3 scripts/dev/sync_palette.py           write plugin/hooks/term/palette.gen.ts
    python3 scripts/dev/sync_palette.py --check   exit 1 (and say so) when that file is not what the tokens give

It reads frontend/src/styles/tokens.css: the chart series --viz-1 to --viz-7 of the default accent (iris) and the label
colors --label-1 to --label-18 (1-12 the places new values take, 13-18 the ones only a pick gives), each resolved on
the light paper (Warm, the default) and on Dark, var() references followed. The terminal draws the light values on a
light Claude Code theme and the Dark values on any other (plugin/hooks/term/paint.ts). A check's color is a label place
1-8 of the same table (backend checks.py COLOURS), so a check's tint in the terminal is the browser's swatch.
frontend/tests/public/viz-palette.test.ts holds the generated file to the tokens.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "frontend" / "src" / "styles" / "tokens.css"
OUT = ROOT / "plugin" / "hooks" / "term" / "palette.gen.ts"

SERIES = [f"--viz-{i}" for i in range(1, 8)]
LABELS = [f"--label-{i}" for i in range(1, 13)]
PICKED = [f"--label-{i}" for i in range(13, 19)]

RULE = re.compile(r"([^{}]+)\{([^{}]*)\}")
HEX = re.compile(r"(--[\w-]+):\s*(#[0-9a-fA-F]{6})\s*;")
REF = re.compile(r"(--[\w-]+):\s*var\((--[\w-]+)\)\s*;")


def rules(css: str, selector: str, pattern: re.Pattern[str]) -> dict[str, str]:
    """The declarations of every rule whose selector, comments dropped and whitespace collapsed, is `selector`, later
    rules over earlier ones."""
    out: dict[str, str] = {}
    for m in RULE.finditer(css):
        sel = re.sub(r"\s+", " ", re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)).strip()
        if sel != selector:
            continue
        body = re.sub(r"/\*.*?\*/", "", m.group(2), flags=re.S)
        for d in pattern.finditer(body):
            out[d.group(1)] = d.group(2).lower() if pattern is HEX else d.group(2)
    return out


def palette(css: str) -> dict[str, list[str]]:
    """Each array palette.gen.ts holds, from the tokens' text."""
    light = rules(css, ":root", HEX)
    papers = {"LIGHT": light, "DARK": {**light, **rules(css, ":root[data-paper='dark']", HEX)}}
    refs = {**rules(css, ":root", REF), **rules(css, ":root, :root[data-accent='iris']", REF)}

    def resolve(name: str, paper: dict[str, str]) -> str:
        n = name
        for _ in range(8):
            if n in paper:
                return paper[n]
            if n not in refs:
                break
            n = refs[n]
        raise SystemExit(f"sync_palette: {name} has no color in {TOKENS.relative_to(ROOT)}")

    out: dict[str, list[str]] = {}
    for paper, values in papers.items():
        out[f"SERIES_{paper}"] = [resolve(n, values) for n in SERIES]
        out[f"LABEL_{paper}"] = [resolve(n, values) for n in LABELS]
        out[f"PICKED_{paper}"] = [resolve(n, values) for n in PICKED]
    return out


def render(p: dict[str, list[str]]) -> str:
    """palette.gen.ts's text: each array on one line."""
    lines = [
        "// Generated by scripts/dev/sync_palette.py from frontend/src/styles/tokens.css: do not edit, run the script.",
        "// The chart series of the default accent and the label colors by place (1-12, then the picked 13-18), on the",
        "// browser's light paper (Warm) and on Dark, so one card has the same colors in the terminal and the browser.",
    ]
    names = ["SERIES_LIGHT", "SERIES_DARK", "LABEL_LIGHT", "LABEL_DARK", "PICKED_LIGHT", "PICKED_DARK"]
    for name in names:
        values = ", ".join(f"'{v}'" for v in p[name])
        lines.append(f"export const {name} = [{values}] as const")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render(palette(TOKENS.read_text(encoding="utf-8")))
    if "--check" in argv:
        now = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if now != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 scripts/dev/sync_palette.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
