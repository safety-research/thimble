// What a label is, and what a field is, said the same way wherever thimble shows its labels beside the data: a label
// is a classifier thimble created and ran over the records; a field is a column already in the data. The Files pane's
// menus head their sections with SourceHeading, each with its own ? (HelpButton, a ringed question mark whose words show
// in the shared tooltip); the Labels sidebar and pane put the labels' ? beside their name; a canvas label card's LABEL
// tag and a label's edit card's "Created by thimble" (ThimbleTag) say the labels' words on hover.
import type { MouseEvent, ReactNode } from 'react'
import { Button } from '../components/Button'
import { Icon } from '../components/Icon'
import { useTooltip } from '../components/Tooltip'

/** what a label is, on the labels' ? and a label card's LABEL tag */
export const LABELS_HELP = 'A label is a classifier created by thimble that ran over your records. A label can be defined via regex, code, or a prompt.'
/** what a field is, on the fields' ? */
export const FIELDS_HELP = 'A field is a column in your own data: a key the records in your files already have.'

/** the section headings of the Files pane's menus */
export const FIELDS_HEADING = "Fields — your data's columns"
export const LABELS_HEADING = 'Labels — generated by thimble'

const stop = (e: MouseEvent) => e.stopPropagation()

/** A small grey tag with thimble's logo, in the style of a label card's LABEL tag (canvas.css .bcell-kind-tag), whose
 * hover says what a label is: a card's LABEL, the edit card's "Created by thimble". */
export function ThimbleTag({ children, className }: { children: ReactNode; className?: string }) {
  const { props, tip } = useTooltip(LABELS_HELP, 'tip-lines')
  return (
    <span className={'bcell-kind-tag' + (className ? ` ${className}` : '')} {...props}>
      <Icon name="thimble" size={11} className="bcell-kind-logo" />
      {children}
      {tip}
    </span>
  )
}

/** The ? that says what labels are, or fields: a borderless icon button, a ringed question mark in the quiet ink that
 * darkens on hover and focus, its words in the tooltip on hover and keyboard focus, wrapped to a few lines. */
export function HelpButton({ of }: { of: 'fields' | 'labels' }) {
  const text = of === 'fields' ? FIELDS_HELP : LABELS_HELP
  const { props, tip } = useTooltip(text, 'tip-lines')
  return (
    <>
      <Button variant="icon" size="sm" icon="circle-help" className="labels-help" aria-label={of === 'fields' ? 'What fields are' : 'What labels are'} onMouseDown={stop} onClick={stop} {...props} />
      {tip}
    </>
  )
}

/** A menu's section heading for the records' fields or thimble's labels, with its ?. */
export function SourceHeading({ of }: { of: 'fields' | 'labels' }) {
  return (
    <div className="menu-heading labels-help-heading" role="presentation">
      {of === 'fields' ? FIELDS_HEADING : LABELS_HEADING}
      <HelpButton of={of} />
    </div>
  )
}
