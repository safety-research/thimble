// @vitest-environment jsdom
// Where a label's values come from, as the canvas's label card and the label's edit card say it (src/canvas/details.ts
// labelIdentity, src/files/LabelCard.tsx): the card's label line names the classifier in plain words, a rule over the
// data or a model's prompt, how many records it ran over and where, and the label it ran within; the Files menus head
// their fields and their labels each with a ? that says what they are, and thimble's tag on a label says on hover what a
// label is; and the class switches are headed by what they do, highlight values in Files, which changes nothing of the
// label.
import { afterEach, beforeAll, expect, test, vi } from 'vitest'
import { classifierWords, labelIdentity } from '../../src/canvas/details.ts'
import { LabelCard, PAINT_TIP } from '../../src/files/LabelCard.tsx'
import { FIELDS_HELP, LABELS_HELP, SourceHeading, ThimbleTag } from '../../src/files/LabelsHelp.tsx'
import type { FilesLabels } from '../../src/files/useLabels.ts'
import { mount, settle, unmountAll } from './mount.tsx'

beforeAll(() => {
  globalThis.ResizeObserver ??= class {
    observe() {}
    unobserve() {}
    disconnect() {}
  } as unknown as typeof ResizeObserver
})
afterEach(() => {
  unmountAll()
  vi.unstubAllGlobals()
})

test('a label card names a rule over the data apart from a model prompt, with what each ran over', () => {
  expect(classifierWords('code')).toBe('Code rule')
  expect(classifierWords('regex')).toBe('Regex rule')
  expect(classifierWords('prompt', 'Opus 5.5')).toBe('Opus 5.5 prompt')
  expect(classifierWords('prompt')).toBe('Prompt')

  // a code rule over every record of its files
  const rule = labelIdentity({ kind: 'code', unit: 'record', glob: 'pool/*.jsonl', n_labeled: 76971, counts: {} })
  expect([rule.how, rule.where]).toEqual(['Code rule', 'over 76,971 records in pool/*.jsonl'])
  // a prompt label that ran only over the records the rule kept
  const judged = labelIdentity({ kind: 'prompt', unit: 'record', glob: 'pool/*.jsonl', n_labeled: 1126, counts: {}, within: { label: 'k1', value: 'kept' } }, 'Opus 5.5', 'kept by request-type rule')
  expect([judged.how, judged.where]).toEqual(['Opus 5.5 prompt', 'over 1,126 records where ‘kept by request-type rule’ is ‘kept’, in pool/*.jsonl'])
  // a trial, and a label not run yet
  expect(labelIdentity({ kind: 'prompt', unit: 'record', glob: 'a.jsonl', n_labeled: 40, counts: {}, trial: true }).where).toBe('over a sample of 40 records in a.jsonl')
  expect(labelIdentity({ kind: 'regex', unit: 'record', glob: 'a.jsonl', counts: {} }).where).toBe('in a.jsonl')
  // a label over the report's sentences
  expect(labelIdentity({ kind: 'prompt', unit: 'span', n_labeled: 3, counts: {} }).where).toBe('over 3 sentences in the report')
})

test('the class switches are headed "Highlight in Files", which says they color values and change nothing of the label', async () => {
  vi.stubGlobal('fetch', async () => new Response('{}', { status: 404, headers: { 'content-type': 'application/json' } }))
  const labels = { all: [], on: [], focus: null, byId: new Map(), presence: new Map(), toggle: () => undefined, save: async () => undefined, remove: async () => undefined } as unknown as FilesLabels
  const el = await mount(<LabelCard ws="w" label={null} labels={labels} appliesTo={['a.jsonl']} onClose={() => undefined} onRun={() => undefined} />)
  await settle()
  expect(el.querySelector('.label-card-classes-head .label-card-hl')?.textContent).toBe('Highlight in Files')
  expect([...el.querySelectorAll('[role="switch"]')].map((s) => s.getAttribute('aria-label'))).toEqual(['Highlight match in Files', 'Highlight no match in Files'])
  expect(PAINT_TIP).toMatch(/color its records in Files/)
  expect(PAINT_TIP).toMatch(/doesn't change the label or its counts/)
})

test("the menus head fields and labels apart, each with a ? that says what it is, and thimble's tag says what a label is", async () => {
  expect(LABELS_HELP).toBe('A label is a classifier created by thimble that ran over your records. A label can be defined via regex, code, or a prompt.')
  expect(FIELDS_HELP).toBe('A field is a column in your own data: a key the records in your files already have.')
  const el = await mount(
    <>
      <SourceHeading of="fields" />
      <SourceHeading of="labels" />
      <ThimbleTag>Created by thimble</ThimbleTag>
    </>,
  )
  expect([...el.querySelectorAll('.menu-heading')].map((h) => h.textContent)).toEqual(["Fields — your data's columns", 'Labels — generated by thimble'])
  const helps = [...el.querySelectorAll<HTMLButtonElement>('button.labels-help')]
  expect(helps.map((b) => b.getAttribute('aria-label'))).toEqual(['What fields are', 'What labels are'])
  // a borderless icon button with the ringed question mark
  for (const b of helps) {
    expect(b.classList.contains('btn-ghost')).toBe(true)
    expect(b.querySelector('svg.icon-circle-help')).not.toBeNull()
  }
  expect(el.querySelector('.bcell-kind-tag svg.icon-thimble')).not.toBeNull()
  expect(el.querySelector('.bcell-kind-tag')?.textContent).toBe('Created by thimble')
})
